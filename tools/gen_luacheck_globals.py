#!/usr/bin/env python3
"""Generate tools/luacheck-wow-globals.lua from Ketho's per-client resource lists for Forever.

    python tools/gen_luacheck_globals.py vendor/BlizzardInterfaceResources/Resources tools/luacheck-wow-globals.lua

Reads GlobalAPI.lua, FrameXML.lua and LuaEnum.lua (plain Lua tables of names; no code is executed)
and writes a Lua file that a .luacheckrc can `dofile`:

    local wow = dofile("../../tools/luacheck-wow-globals.lua")
    std = "lua51"
    read_globals = wow.read_globals   -- API functions, namespaces (C_*), FrameXML globals, Enum, constants

Dotted names (`C_ChatInfo.SendAddonMessage`, `AchievementUtil.IsCategoryFeatOfStrength`) collapse to
their first segment: luacheck treats a table global as fully readable. Run by tools\vendor-sync.ps1.
"""
import re
import sys
from pathlib import Path

NAME = re.compile(r'^\s*"([A-Za-z_][A-Za-z0-9_.]*)"\s*,?\s*$')
ENUM_KEY = re.compile(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*\{")

# Lua-side globals the client adds that the resource lists do not spell out.
EXTRA = """
bit strlenutf8 strtrim strsplit strjoin strconcat tostringall getglobal setglobal
issecretvalue canaccessvalue issecurevariable forceinsecure securecall hooksecurefunc
debugstack debuglocals geterrorhandler seterrorhandler scrub
date time difftime fastrandom
CreateFrame CreateFont CreateFramePool GetBuildInfo GetLocale GetTime
WOW_PROJECT_ID WOW_PROJECT_MAINLINE WOW_PROJECT_CAMELOT WOW_PROJECT_CLASSIC
UIParent WorldFrame GameTooltip GameFontNormal GameFontHighlight ChatFontNormal
SlashCmdList SLASH_RELOAD1 DEFAULT_CHAT_FRAME ChatFrame1 NUM_CHAT_WINDOWS
Settings SettingsPanel MenuUtil Mixin CreateFromMixins CallbackRegistryMixin
C_AddOns C_ChatInfo C_Timer C_Secrets C_GameRules C_CVar C_Item C_Spell C_UnitAuras
LibStub
""".split()


def names_from(path: Path) -> set[str]:
    out = set()
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        m = NAME.match(line)
        if m:
            out.add(m.group(1).split(".")[0])
    return out


def main(argv) -> int:
    if len(argv) != 3:
        print(__doc__)
        return 2
    res, dest = Path(argv[1]), Path(argv[2])
    globs = set(EXTRA)
    for f in ("GlobalAPI.lua", "FrameXML.lua"):
        p = res / f
        if p.exists():
            globs |= names_from(p)
        else:
            print(f"warning: {p} missing", file=sys.stderr)
    if (res / "LuaEnum.lua").exists():
        globs.add("Enum")
        for line in (res / "LuaEnum.lua").read_text(encoding="utf-8", errors="replace").splitlines():
            if line.startswith(("NUM_", "LE_", "MAX_")) or re.match(r"^[A-Z][A-Z0-9_]+\s*=", line):
                globs.add(line.split("=")[0].strip())
    names = sorted(globs)
    body = ",\n".join(f'  "{n}"' for n in names)
    dest.write_text(
        "-- Generated by tools/gen_luacheck_globals.py from Ketho/BlizzardInterfaceResources (forever).\n"
        "-- Do not edit; run tools\\vendor-sync.ps1.\n"
        f"return {{ read_globals = {{\n{body}\n}} }}\n",
        encoding="utf-8",
    )
    print(f"{len(names)} globals -> {dest}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
